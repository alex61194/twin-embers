#!/usr/bin/env python3
"""Builds the logo of the lower screen's idle backdrop: 3ds_port/include/idle_logo.h.

The lower screen shows the ember backdrop with the project's own banner (docs/media/twin-embers-banner.png) while
FireRed's screen on the upper one has nothing for it (the title, naming, a shop, an evolution, a trade ...). The banner
is the port's own art (no game pixels); it is reduced here to LOGO_W pixels across and to 256 colours with their
alpha (RGB565 and 0-15), one byte a pixel.

Needs Pillow; it is a development tool and its output is committed. Run it again after changing the banner.
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'docs/media/twin-embers-banner.png'
OUT = ROOT / '3ds_port/include/idle_logo.h'
LOGO_W = 224


def main():
    im = Image.open(SRC).convert('RGBA')
    h = round(im.height * LOGO_W / im.width)
    im = im.resize((LOGO_W, h), Image.LANCZOS)
    q = im.quantize(colors=256, method=Image.Quantize.FASTOCTREE)
    pal = q.getpalette('RGBA') or []
    pal += [0] * (1024 - len(pal))
    colours = [(pal[i] >> 3) << 11 | (pal[i + 1] >> 2) << 5 | (pal[i + 2] >> 3) for i in range(0, 1024, 4)]
    alphas = [(pal[i + 3] * 15 + 127) // 255 for i in range(0, 1024, 4)]
    index = list(q.tobytes())
    lines = ['/* Generated by tools/make_idle_logo.py from docs/media/twin-embers-banner.png. Do not edit. */',
             '#ifndef IDLE_LOGO_H', '#define IDLE_LOGO_H', '#include <stdint.h>',
             f'#define IDLE_LOGO_W {LOGO_W}', f'#define IDLE_LOGO_H_PX {h}',
             '/* The colours (RGB565) and their alpha (0-15). */',
             'static const uint16_t kIdleLogoColour[256] = {']
    for i in range(0, 256, 16):
        lines.append('    ' + ', '.join(f'0x{c:04x}' for c in colours[i:i + 16]) + ',')
    lines += ['};', 'static const uint8_t kIdleLogoAlpha[256] = {']
    for i in range(0, 256, 32):
        lines.append('    ' + ','.join(str(c) for c in alphas[i:i + 32]) + ',')
    lines += ['};', '/* A colour a pixel, row by row. */', 'static const uint8_t kIdleLogo[IDLE_LOGO_W * IDLE_LOGO_H_PX] = {']
    for i in range(0, len(index), 32):
        lines.append('    ' + ','.join(str(c) for c in index[i:i + 32]) + ',')
    lines += ['};', '#endif', '']
    OUT.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
