#!/usr/bin/env python3
"""Builds the battle action screen's skin from its artwork.

The artwork is the whole lower screen while the player chooses an action (docs/media/battle-action.png) and its four
cards as pictures (battle-action-fight / bag / pokemon / run.png, 137x64, exact crops of it). It is used as painted;
this script takes out what a battle changes and writes 3ds_port/include/battle_action_skin.h with its backdrop in
quarters (battle_action_skin_bg0.h .. bg3.h) and the cards (battle_action_skin_cards0.h, cards1.h):

* the backdrop: the artwork with the party's balls, HP bars, status capsule and percentage, the cards and the footer's
  name, level, HP and message taken out (each row filled from its free columns);
* the party's pictures, as the move screen's: a ball, a fainted ball, the lead's with its glow, the HP track, the PAR
  capsule; the HP bar's colours;
* the four cards.

Needs Pillow; it is a development tool and its output is committed. Run it again after changing the artwork.
"""
from pathlib import Path

from PIL import Image

import make_move_skin as msk

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'docs/media'
OUT = ROOT / '3ds_port/include/battle_action_skin.h'
BG_PARTS = 4
CARDS = [('fight', (20, 56)), ('bag', (162, 56)), ('pokemon', (20, 124)), ('run', (162, 124))]   # by action number 0..3
CARD_W, CARD_H = 137, 64
CARD_FREE = [17, 18, 19, 158, 159, 160, 161, 300, 301, 302, 303]
# The footer: what a battle changes (x0, y0, x1, y1, exclusive) and the columns each is filled from.
FOOT_BOXES = [((52, 198, 92, 207), range(100, 140)), ((163, 198, 176, 207), range(180, 210)),
              ((229, 198, 271, 207), range(180, 210)), ((271, 198, 301, 207), range(304, 308)),
              ((14, 211, 290, 227), range(150, 290))]
HP_BAR = (232, 201, 268, 204)                                 # x0, y0, x1, y1: 36 x 3, drawn by the screen
NAME = (53, 200)                                              # the name's first column and row (tiny lettering, 6 rows)
LEVEL = (165, 200)
HP_TEXT_RIGHT, HP_TEXT_Y = 298, 200
MESSAGE = (22, 214)
MAX_NAME = 8


def rgb565(c):
    return msk.rgb565(c)


def main():
    art = Image.open(ART / 'battle-action.png').convert('RGB')
    assert art.size == (320, 240)
    px = art.load()
    bg = art.copy()
    bp = bg.load()
    msk.inpaint_rows(bp, msk.STRIP, msk.STRIP_FREE)
    for box, free in FOOT_BOXES:
        msk.inpaint_rows(bp, box, free)
    for name, (cx, cy) in CARDS:
        card = Image.open(ART / ('battle-action-%s.png' % name)).convert('RGB')
        assert card.size == (CARD_W, CARD_H) and all(px[cx + u, cy + v] == card.getpixel((u, v))
                                                     for u in range(CARD_W) for v in range(CARD_H)), name
    for y in range(53, 193):                                  # the cards' places and the glow round them: the body's own rows
        c = msk.median(bp[x, y] for x in (17, 18, 19))
        for x in range(14, 306):
            bp[x, y] = c
    S = msk.SLOT_X
    hp_green = [msk.median(px[x, y] for x in range(32, 57)) for y in range(42, 47)]
    hp_yellow = [msk.median(px[x, y] for x in range(76, 88)) for y in range(42, 47)]
    label_ink = msk.median(px[x, y] for x in range(165, 173) for y in range(200, 206) if px[x, y][0] > 200 and px[x, y][2] < 100)
    name_ink = (248, 252, 248)
    shots = [('kAbBall', msk.crop(art, S[2] + msk.BALL[0], msk.BALL[1], msk.BALL[2], msk.BALL[3])),
             ('kAbBallFaint', msk.crop(art, S[3] + msk.BALL[0], msk.BALL[1], msk.BALL[2], msk.BALL[3])),
             ('kAbBallLead', msk.crop(art, S[0] + msk.BALL_LEAD[0], msk.BALL_LEAD[1], msk.BALL_LEAD[2], msk.BALL_LEAD[3])),
             ('kAbTrack', msk.crop(art, S[3] + msk.TRACK[0], msk.TRACK[1], msk.TRACK[2], msk.TRACK[3])),
             ('kAbPar', msk.crop(art, *msk.PAR))]
    out = ['/* Generated by tools/make_action_skin.py from docs/media/battle-action*.png (the battle action screen\'s artwork).',
           ' * Do not edit: change the artwork and run the script again. */',
           '#ifndef BATTLE_ACTION_SKIN_H', '#define BATTLE_ACTION_SKIN_H', '', '#include <stdint.h>', '']
    out.append('#define AB_CARD_W %d\n#define AB_CARD_H %d' % (CARD_W, CARD_H))
    out.append('static const int16_t kAbCardPos[4][2] = {%s};   /* by the controller\'s action number */' % ', '.join('{%d, %d}' % p for _, p in CARDS))
    out.append('#define AB_BALL_U %d\n#define AB_BALL_V %d\n#define AB_BALL_W %d\n#define AB_BALL_H %d' % msk.BALL)
    out.append('#define AB_LEAD_U %d\n#define AB_LEAD_V %d\n#define AB_LEAD_W %d\n#define AB_LEAD_H %d' % msk.BALL_LEAD)
    out.append('#define AB_TRACK_U %d\n#define AB_TRACK_V %d\n#define AB_TRACK_W %d\n#define AB_TRACK_H %d' % msk.TRACK)
    out.append('#define AB_PAR_X %d\n#define AB_PAR_Y %d\n#define AB_PAR_W %d\n#define AB_PAR_H %d' % msk.PAR)
    out.append('#define AB_STRIP_X0 %d\n#define AB_STRIP_Y0 %d\n#define AB_STRIP_X1 %d\n#define AB_STRIP_Y1 %d' % msk.STRIP)
    out.append('#define AB_FOOT_X0 12\n#define AB_FOOT_Y0 196\n#define AB_FOOT_X1 308\n#define AB_FOOT_Y1 228')
    out.append('#define AB_HPBAR_X %d\n#define AB_HPBAR_Y %d\n#define AB_HPBAR_W %d\n#define AB_HPBAR_H %d'
                % (HP_BAR[0], HP_BAR[1], HP_BAR[2] - HP_BAR[0], HP_BAR[3] - HP_BAR[1]))
    out.append('#define AB_NAME_X %d\n#define AB_NAME_Y %d\n#define AB_LEVEL_X %d\n#define AB_LEVEL_Y %d' % (NAME + LEVEL))
    out.append('#define AB_HPTEXT_RIGHT %d\n#define AB_HPTEXT_Y %d\n#define AB_MESSAGE_X %d\n#define AB_MESSAGE_Y %d'
               % (HP_TEXT_RIGHT, HP_TEXT_Y, MESSAGE[0], MESSAGE[1]))
    out.append('static const int16_t kAbSlotX[6] = {%s};' % ', '.join(map(str, S)))
    out.append('static const uint8_t kAbHpGreen[5][3] = {%s};' % ', '.join('{%d, %d, %d}' % c for c in hp_green))
    out.append('static const uint8_t kAbHpYellow[5][3] = {%s};' % ', '.join('{%d, %d, %d}' % c for c in hp_yellow))
    out.append('static const uint8_t kAbLevelInk[3] = {%d, %d, %d};' % tuple(label_ink))
    rows_per = 240 // BG_PARTS
    out.append('/* The backdrop, RGB565, in quarters of %d rows. */' % rows_per)
    for part in range(BG_PARTS):
        out.append('#include "battle_action_skin_bg%d.h"' % part)
        body = msk.c_rows('kAbBg%d[%d][320]' % (part, rows_per), 'uint16_t', msk.crop(bg, 0, part * rows_per, 320, rows_per),
                          lambda c: '0x%04X' % rgb565(c), 20)
        (OUT.parent / ('battle_action_skin_bg%d.h' % part)).write_text(
            '/* Generated by tools/make_action_skin.py: the action screen\'s backdrop, rows %d-%d. Do not edit. */\n%s'
            % (part * rows_per, part * rows_per + rows_per - 1, body))
    out.append('static const uint16_t (*const kAbBg[%d])[320] = {%s};' % (BG_PARTS, ', '.join('kAbBg%d' % i for i in range(BG_PARTS))))
    out.append('#define AB_BG(x, y) (kAbBg[(y) / %d][(y) %% %d][x])' % (rows_per, rows_per))
    out.append('/* The four cards as painted (RGB565), by action number: FIGHT, BAG, POKeMON, RUN. */')
    for part in range(2):
        name = 'battle_action_skin_cards%d.h' % part
        out.append('#include "%s"' % name)
        body = ''
        for k in (2 * part, 2 * part + 1):
            card = Image.open(ART / ('battle-action-%s.png' % CARDS[k][0])).convert('RGB')
            body += msk.c_rows('kAbCard%d[AB_CARD_H][AB_CARD_W]' % k, 'uint16_t', msk.crop(card, 0, 0, CARD_W, CARD_H),
                               lambda c: '0x%04X' % rgb565(c), 20)
        (OUT.parent / name).write_text('/* Generated by tools/make_action_skin.py: the action cards %d-%d. Do not edit. */\n%s'
                                       % (2 * part, 2 * part + 1, body))
    out.append('static const uint16_t (*const kAbCard[4])[AB_CARD_W] = {kAbCard0, kAbCard1, kAbCard2, kAbCard3};')
    for name, rows in shots:
        out.append(msk.c_rows('%s[%d][%d]' % (name, len(rows), len(rows[0])), 'uint16_t', rows, lambda c: '0x%04X' % rgb565(c)))
    out.append('')
    out.append('#endif')
    OUT.write_text('\n'.join(out) + '\n')
    bg.save('/tmp/ab_bg.png')
    print('wrote', OUT.relative_to(ROOT), 'level ink', label_ink)


if __name__ == '__main__':
    main()
