#!/usr/bin/env python3
"""Write data/event_scripts.s for the Spanish build from the two layouts.

The object only needs the Spanish shape: its size, every label at its Spanish
offset and every pointer site with its target. rex_objects.py turns the section
into NOBITS and the Spanish ROM's bytes arrive from the pack, so the gaps are
`.space` and nothing of the ROM is written here.

  gen_event_scripts_es.py event_scripts_layout_us.json event_scripts_layout_es.json out.s
"""
import json
import sys


def main(us_path, es_path, out_path):
    us = json.load(open(us_path))
    es = json.load(open(es_path))
    pos = {int(k): v for k, v in es['pos']}           # USA offset of a label -> Spanish offset
    size = es['es_size']
    local = {}
    for off, name, glob in us['syms']:
        local.setdefault(name, off)
    by_us = {r[0]: r for r in us['relocs']}
    lines = ['@ Generated by tools/lang_es/gen_event_scripts_es.py: the Spanish layout of event_scripts.',
             '\t.section script_data, "aw", %progbits', '\t.align 2']
    marks = []                                          # (spanish offset, order, text)
    for off, name, glob in us['syms']:
        if off not in pos:
            raise SystemExit(f'label without a Spanish offset: {name}')
        if glob:
            marks.append((pos[off], 0, f'\t.global {name}'))
        marks.append((pos[off], 1, f'{name}:'))
    for es_off, us_off in es['sites']:
        r = by_us.get(us_off)
        if r is None:
            raise SystemExit(f'pointer site without a USA relocation: {us_off}')
        _, _, sym, add = r
        if sym == 'script_data' or sym in local:
            base = local.get(sym, 0) + add
            if base not in pos:
                raise SystemExit(f'pointer into event_scripts at {base} has no Spanish label')
            target = f'__es_script_data+{pos[base]}'
        else:
            target = sym if add == 0 else f'{sym}+{add}'
        marks.append((es_off, 2, ('ptr', target)))
    marks.sort(key=lambda m: (m[0], m[1]))
    lines.append('__es_script_data:')
    at = 0
    for off, kind, text in marks:
        if off < at:
            raise SystemExit(f'overlapping item at {off} (already at {at})')
        if off > at:
            lines.append(f'\t.space {off - at}')
            at = off
        if kind == 2:
            lines.append(f'\t.4byte {text[1]}')
            at += 4
        else:
            lines.append(text)
    if size > at:
        lines.append(f'\t.space {size - at}')
    open(out_path, 'w').write('\n'.join(lines) + '\n')
    print(f'{out_path}: {size} bytes, {len(us["syms"])} labels, {len(es["sites"])} pointer sites')


if __name__ == '__main__':
    main(*sys.argv[1:4])
