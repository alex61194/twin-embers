void CtrTouchText_PartyMessage(const unsigned char *str, char *out, unsigned size)
{
    unsigned i = 0, o = 0;

    while (str[i] != EOS && o + 4 < size)
    {
        unsigned char c = str[i++];

        if (c == EXT_CTRL_CODE_BEGIN)
        {
            unsigned char n = GetExtCtrlCodeLength(str[i]);
            i += n ? n : 1;
            continue;
        }
        if (c >= CHAR_A && c <= CHAR_Z)
            out[o++] = (char)('A' + (c - CHAR_A));
        else if (c >= CHAR_a && c <= CHAR_z)
            out[o++] = (char)('a' + (c - CHAR_a));
        else if (c >= CHAR_0 && c <= CHAR_9)
            out[o++] = (char)('0' + (c - CHAR_0));
        else if (c == CHAR_e_ACUTE)
        {
            out[o++] = (char)0xC3;
            out[o++] = (char)0xA9;
        }
        else if (c == CHAR_E_ACUTE)
            out[o++] = 'E';
        else if (c == CHAR_ELLIPSIS)
        {
            out[o++] = '.';
            out[o++] = '.';
            out[o++] = '.';
        }
        else
        {
            char ch = c == CHAR_PERIOD ? '.' : c == CHAR_COMMA ? ',' : c == CHAR_EXCL_MARK ? '!' : c == CHAR_QUESTION_MARK ? '?'
                    : c == CHAR_HYPHEN ? '-' : c == CHAR_SLASH ? '/' : c == CHAR_COLON ? ':' : c == CHAR_PERCENT ? '%'
                    : c == CHAR_LEFT_PAREN ? '(' : c == CHAR_RIGHT_PAREN ? ')' : ' ';

            if (ch != ' ' || (o > 0 && out[o - 1] != ' '))
                out[o++] = ch;
        }
    }
    while (o > 0 && out[o - 1] == ' ')
        --o;
    out[o] = 0;
}
